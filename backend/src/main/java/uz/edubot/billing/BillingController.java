package uz.edubot.billing;

import jakarta.validation.Valid;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;
import uz.edubot.billing.BillingRepository.ChargeRow;
import uz.edubot.billing.BillingRepository.PaymentRow;
import uz.edubot.billing.BillingService.Balance;
import uz.edubot.billing.BillingService.Debtors;
import uz.edubot.common.web.Pages;
import uz.edubot.security.CurrentMember;
import uz.edubot.student.StudentService;

@RestController
@RequestMapping("/api/v1")
@RequiredArgsConstructor
class BillingController {

    private final BillingService billingService;
    private final StudentService studentService;

    @GetMapping("/students/{id}/balance")
    @PreAuthorize("hasAuthority('PAYMENT_READ')")
    BalanceResponse balance(@PathVariable UUID id) {
        studentService.get(id);
        return BalanceResponse.of(billingService.balance(id));
    }

    /**
     * @param idempotencyKey generated by the client once per payment form; a retry with the same key
     *                       returns the already recorded payment instead of creating a second one
     */
    @PostMapping("/students/{id}/payments")
    @ResponseStatus(HttpStatus.CREATED)
    @PreAuthorize("hasAuthority('PAYMENT_WRITE')")
    BalanceResponse pay(@AuthenticationPrincipal CurrentMember member, @PathVariable UUID id,
                        @RequestHeader("Idempotency-Key") @Size(min = 8, max = 100) String idempotencyKey,
                        @Valid @RequestBody PaymentRequest request) {
        studentService.get(id);
        billingService.recordPayment(member, id, request.amount(), request.method(), blankToNull(request.note()),
                request.chargeId(), idempotencyKey);
        return BalanceResponse.of(billingService.balance(id));
    }

    @PostMapping("/payments/{id}/void")
    @PreAuthorize("hasAuthority('PAYMENT_VOID')")
    Map<String, String> voidPayment(@AuthenticationPrincipal CurrentMember member, @PathVariable UUID id,
                                    @Valid @RequestBody ReasonRequest request) {
        billingService.voidPayment(member, id, request.reason().strip());
        return Map.of("status", "VOIDED");
    }

    @PutMapping("/charges/{id}")
    @PreAuthorize("hasAuthority('PAYMENT_VOID')")
    ChargeDto changeCharge(@AuthenticationPrincipal CurrentMember member, @PathVariable UUID id,
                           @Valid @RequestBody ChargeAmountRequest request) {
        return ChargeDto.of(billingService.changeChargeAmount(member, id, request.amount(), request.reason().strip()));
    }

    @PostMapping("/charges/{id}/void")
    @PreAuthorize("hasAuthority('PAYMENT_VOID')")
    ChargeDto voidCharge(@AuthenticationPrincipal CurrentMember member, @PathVariable UUID id,
                         @Valid @RequestBody ReasonRequest request) {
        return ChargeDto.of(billingService.voidCharge(member, id, request.reason().strip()));
    }

    /** Manual trigger of the (idempotent) monthly charge generation. */
    @PostMapping("/billing/periods/{month}/generate")
    @PreAuthorize("hasAuthority('PAYMENT_WRITE')")
    Map<String, Integer> generate(@PathVariable YearMonth month) {
        return Map.of("studentsCharged", billingService.generateForMonth(month));
    }

    @PostMapping("/debtors/{studentId}/remind")
    @PreAuthorize("hasAuthority('PAYMENT_WRITE')")
    Map<String, Integer> remind(@PathVariable UUID studentId) {
        studentService.get(studentId);
        return Map.of("queued", billingService.remindNow(studentId));
    }

    @GetMapping("/debtors")
    @PreAuthorize("hasAuthority('PAYMENT_READ')")
    DebtorsResponse debtors(@RequestParam(required = false) UUID groupId,
                            @RequestParam(defaultValue = "0") int page,
                            @RequestParam(defaultValue = "30") int size) {
        int safeSize = Math.clamp(size, 1, Pages.MAX_SIZE);
        return DebtorsResponse.of(billingService.debtors(groupId, Math.max(page, 0), safeSize));
    }

    private static String blankToNull(String value) {
        return value == null || value.isBlank() ? null : value.strip();
    }

    // ---- DTOs ----

    record PaymentRequest(@NotNull @Positive @Digits(integer = 13, fraction = 2) BigDecimal amount,
                          @NotNull @Pattern(regexp = "CASH|CARD|TRANSFER|OTHER") String method,
                          @Size(max = 500) String note,
                          UUID chargeId) {
    }

    record ReasonRequest(@NotBlank @Size(max = 500) String reason) {
    }

    record ChargeAmountRequest(@NotNull @PositiveOrZero @Digits(integer = 13, fraction = 2) BigDecimal amount,
                               @NotBlank @Size(max = 500) String reason) {
    }

    record ChargeDto(UUID id, UUID groupId, String groupName, LocalDate periodStart, LocalDate periodEnd,
                     BigDecimal amount, BigDecimal paidAmount, LocalDate dueDate, String status, String paymentStatus) {

        static ChargeDto of(ChargeRow c) {
            String paymentStatus = "VOID".equals(c.status()) ? "VOID"
                    : c.paidAmount().compareTo(c.amount()) >= 0 ? "PAID"
                    : c.paidAmount().signum() > 0 ? "PARTIAL" : "UNPAID";
            return new ChargeDto(c.id(), c.groupId(), c.groupName(), c.periodStart(), c.periodEnd(), c.amount(),
                    c.paidAmount(), c.dueDate(), c.status(), paymentStatus);
        }
    }

    record PaymentDto(UUID id, BigDecimal amount, BigDecimal allocated, String method, Instant paidAt, String note,
                      String status, String voidReason, String receivedBy) {

        static PaymentDto of(PaymentRow p) {
            return new PaymentDto(p.id(), p.amount(), p.allocated(), p.method(), p.paidAt(), p.note(), p.status(),
                    p.voidReason(), p.receivedByName());
        }
    }

    record BalanceResponse(BigDecimal debt, BigDecimal credit, List<ChargeDto> charges, List<PaymentDto> payments) {

        static BalanceResponse of(Balance b) {
            return new BalanceResponse(b.debt(), b.credit(), b.charges().stream().map(ChargeDto::of).toList(),
                    b.payments().stream().map(PaymentDto::of).toList());
        }
    }

    record DebtorDto(UUID studentId, String firstName, String lastName, String phone, String guardianPhone,
                     BigDecimal debt, LocalDate oldestDue) {
    }

    record DebtorsResponse(long students, BigDecimal total, List<DebtorDto> items) {

        static DebtorsResponse of(Debtors d) {
            return new DebtorsResponse(d.students(), d.total(), d.items().stream()
                    .map(x -> new DebtorDto(x.row().studentId(), x.row().firstName(), x.row().lastName(),
                            x.row().phone(), x.guardianPhone(), x.row().debt(), x.row().oldestDue()))
                    .toList());
        }
    }
}
